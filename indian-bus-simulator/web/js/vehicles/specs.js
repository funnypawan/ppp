export const BUS_SPEC_BY_ID = Object.fromEntries(BUS_SPECS.map((b) => [b.id, b]));

export function getBusSpec(id) {
  return BUS_SPEC_BY_ID[id] || BUS_SPECS[0];
}

/** Peak power expressed as engine torque available at a given rpm (Nm). */
export function engineTorque(spec, rpm) {
  const idle = spec.idleRpm;
  const max = spec.maxRpm;
  const peak = spec.peakTorque;
  const r = Math.max(0.0001, (rpm - idle) / (max - idle));
  // Diesel bus engines make nearly full torque from idle upwards, hold a
  // broad plateau and taper gently towards the red line.
  let shape;
  if (r < 0.1) shape = 0.88 + (r / 0.1) * 0.12;
  else if (r <= 0.78) shape = 1;
  else shape = 1 - ((r - 0.78) / 0.22) * 0.32;
  return peak * shape;
}

/** Ratio of the currently selected gear (1-indexed gears, 0 = neutral, -1 = reverse). */
export function gearRatio(spec, gear) {
  if (gear === 0) return 0;
  if (gear < 0) return -spec.reverseRatio;
  const idx = Math.abs(gear) - 1;
  return spec.gearRatios[Math.min(idx, spec.gearRatios.length - 1)];
}

/** Total seat capacity of a bus spec. */
export function seatCapacity(spec) {
  const base = spec.seatRows * spec.seatsPerRow;
  const upper = spec.upperDeckRows ? spec.upperDeckRows * spec.upperDeckSeatsPerRow : 0;
  const berths = spec.berthRows ? spec.berthRows * 2 : 0;
  return base + upper + berths;
}
